/* ------------------------------------------------------------------ links */

function applyConfig() {
  document.querySelectorAll('[data-link]').forEach((el) => {
    const key = el.dataset.link;
    const url = (CONFIG[key] || '').trim();

    if (url && /^https?:\/\//i.test(url)) {
      el.href = url;
      el.classList.remove('is-pending');
      el.removeAttribute('title');
      if (url.includes('discord.com') || url.includes('discord.gg')) {
        el.target = '_blank';
        el.rel = 'noopener noreferrer';
      }
      return;
    }

    el.href = '#support';
    el.classList.add('is-pending');
    el.title = LABELS[key] + ' is not set yet — add it in CONFIG inside app.js.';
  });

  // Hide the pair of CTA links while neither destination exists.
  if (!CONFIG.community.trim() && !CONFIG.support.trim()) {
    const row = document.querySelector('.cta-links');
    if (row) row.hidden = true;
  }
}

/* ------------------------------------------------------------------- auth */

function setupAuthUI() {
  if (!window.KernelAuth) return;

  const signedIn = Boolean(window.KernelAuth.session());
  const http = window.location.protocol === 'http:' || window.location.protocol === 'https:';

  document.querySelectorAll('[data-login]').forEach((el) => {
    el.href = 'dashboard.html';

    // Build the authorize URL on click so the state is generated once, not
    // overwritten by every login link on the page.
    if (!signedIn && http) {
      el.addEventListener('click', (event) => {
        event.preventDefault();
        window.location.href = window.KernelAuth.loginUrl();
      });
    }

    el.querySelectorAll('[data-login-label]').forEach((label) => {
      const out = label.dataset.loginLabel || 'Log in';
      const inside = label.dataset.loginLabelSignedIn || 'Dashboard';
      label.textContent = signedIn ? inside : out;
    });
  });
}

/* -------------------------------------------------------------------- nav */

function setupNav() {
  const nav = document.querySelector('.nav');
  const drawer = document.getElementById('drawer');
  const burger = document.getElementById('burger');
  const explore = document.getElementById('explore');
  const exploreWrap = explore ? explore.closest('.nav-more') : null;
  let lastFocus = null;

  function setDrawer(open) {
    if (!drawer || !burger) return;
    drawer.classList.toggle('is-open', open);
    burger.setAttribute('aria-expanded', String(open));
    burger.setAttribute('aria-label', open ? 'Close menu' : 'Open menu');
    document.body.classList.toggle('drawer-open', open);

    if (open) {
      lastFocus = document.activeElement;
      const first = drawer.querySelector('a');
      if (first) window.requestAnimationFrame(() => first.focus({ preventScroll: true }));
    } else if (lastFocus && typeof lastFocus.focus === 'function') {
      lastFocus.focus({ preventScroll: true });
      lastFocus = null;
    }
  }

  function setExplore(open, restoreFocus) {
    if (!explore || !exploreWrap) return;
    exploreWrap.classList.toggle('is-open', open);
    explore.setAttribute('aria-expanded', String(open));
    document.body.classList.toggle('explore-open', open);
    if (!open && restoreFocus) explore.focus({ preventScroll: true });
  }

  function navState() {
    if (nav) nav.classList.toggle('is-stuck', window.scrollY > 6);
  }

  if (burger && drawer) {
    burger.addEventListener('click', () => setDrawer(burger.getAttribute('aria-expanded') !== 'true'));
    drawer.addEventListener('click', (event) => {
      if (event.target === drawer) setDrawer(false);
      else if (event.target.closest('a')) setDrawer(false);
    });
  }

  if (explore && exploreWrap) {
    explore.addEventListener('click', (event) => {
      event.stopPropagation();
      setExplore(explore.getAttribute('aria-expanded') !== 'true');
    });
    exploreWrap.querySelectorAll('.nav-menu a').forEach((link) => {
      link.addEventListener('click', () => setExplore(false));
    });
    document.addEventListener('click', (event) => {
      if (!exploreWrap.contains(event.target)) setExplore(false);
    });
  }

  document.addEventListener('keydown', (event) => {
    if (event.key !== 'Escape') return;
    if (exploreWrap && exploreWrap.classList.contains('is-open')) {
      setExplore(false, true);
      return;
    }
    if (drawer && drawer.classList.contains('is-open')) setDrawer(false);
  });

  window.addEventListener('resize', () => {
    if (window.innerWidth > 900 && drawer && drawer.classList.contains('is-open')) setDrawer(false);
  });

  navState();
  let ticking = false;
  window.addEventListener(
    'scroll',
    () => {
      if (ticking) return;
      ticking = true;
      window.requestAnimationFrame(() => {
        navState();
        ticking = false;
      });
    },
    { passive: true },
  );
}

/* ----------------------------------------------------------------- reveal */

function setupReveals() {
  const items = Array.from(document.querySelectorAll('[data-reveal]'));
  if (!items.length) return;

  if (!('IntersectionObserver' in window)) {
    items.forEach((el) => el.classList.add('is-in'));
    return;
  }

  const io = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        const el = entry.target;
        const siblings = Array.from(el.parentElement.children).filter((child) =>
          child.hasAttribute('data-reveal'),
        );
        el.style.transitionDelay = Math.min(siblings.indexOf(el), 3) * 70 + 'ms';
        el.classList.add('is-in');
        io.unobserve(el);
        window.setTimeout(() => {
          el.style.transitionDelay = '';
        }, 900);
      });
    },
    { rootMargin: '0px 0px -6% 0px', threshold: 0.05 },
  );

  items.forEach((el) => io.observe(el));
}

/* ------------------------------------------------------- command directory */

function setupDirectory() {
  const root = document.querySelector('[data-cmd-dir]');
  if (!root) return;

  const buttons = Array.from(root.querySelectorAll('.cmd-filters button'));
  const groups = Array.from(root.querySelectorAll('.cmd-group'));
  const rows = Array.from(root.querySelectorAll('[data-cmd]'));
  const search = root.querySelector('.cmd-search input');
  const empty = root.querySelector('.cmd-empty');
  const total = root.querySelector('.cmd-total b');
  const totalLabel = root.querySelector('.cmd-total span');
  const defaultLabel = totalLabel ? totalLabel.textContent : 'slash commands';
  let filter = 'all';

  function apply() {
    const query = (search ? search.value : '').trim().toLowerCase();
    let shown = 0;

    rows.forEach((row) => {
      const group = row.closest('.cmd-group');
      const inFilter = filter === 'all' || (group && group.dataset.group === filter);
      const matches = inFilter && (!query || row.textContent.toLowerCase().includes(query));
      row.hidden = !matches;
      if (matches) shown += 1;
    });

    groups.forEach((group) => {
      group.hidden = !Array.from(group.querySelectorAll('[data-cmd]')).some((row) => !row.hidden);
    });

    const active = filter !== 'all' || query.length > 0;
    root.classList.toggle('is-filtered', active);
    if (empty) empty.hidden = shown > 0;
    if (total) total.textContent = String(active ? shown : rows.length);
    if (totalLabel) totalLabel.textContent = active ? 'commands shown' : defaultLabel;
  }

  buttons.forEach((button) => {
    button.addEventListener('click', () => {
      filter = button.dataset.filter || 'all';
      buttons.forEach((other) => {
        const isActive = other === button;
        other.classList.toggle('is-active', isActive);
        other.setAttribute('aria-pressed', String(isActive));
      });
      apply();
    });
  });

  if (search) {
    search.addEventListener('input', apply);
    search.addEventListener('keydown', (event) => {
      if (event.key !== 'Escape' || !search.value) return;
      event.stopPropagation();
      search.value = '';
      apply();
    });
  }
}

/* ----------------------------------------------------------------- servers */

function formatCount(value) {
  const number = Number(value);
  if (!Number.isFinite(number) || number <= 0) return '';
  if (number < 1000) return String(Math.round(number));
  return new Intl.NumberFormat('en', {
    notation: 'compact',
    maximumFractionDigits: 1,
  }).format(number);
}

function initials(name) {
  const words = String(name)
    .replace(/[^\p{L}\p{N}\s]/gu, ' ')
    .trim()
    .split(/\s+/)
    .filter(Boolean);
  if (!words.length) return 'K';
  return words
    .slice(0, 2)
    .map((word) => word[0])
    .join('')
    .toUpperCase();
}

function paletteFor(id) {
  let hash = 0;
  const text = String(id || '');
  for (let i = 0; i < text.length; i += 1) hash = (hash * 31 + text.charCodeAt(i)) >>> 0;
  return PALETTES[hash % PALETTES.length];
}

function serverHref(server) {
  const id = server && server.id ? String(server.id) : '';
  return id && !id.startsWith('example-') ? 'server.html?id=' + encodeURIComponent(id) : '';
}

function serverCard(server) {
  const href = serverHref(server);
  const card = document.createElement(href ? 'a' : 'div');
  card.className = 'server-card';
  if (href) {
    card.href = href;
    card.setAttribute('aria-label', server.name + ' — open the server page');
  }
  const members = formatCount(server.memberCount);
  card.title = server.name + (members ? ` — ${members} members` : '');

  const icon = document.createElement('span');
  icon.className = 'server-icon';
  const [c1, c2] = paletteFor(server.id || server.name);
  icon.style.setProperty('--c1', c1);
  icon.style.setProperty('--c2', c2);

  // The bot sends a full CDN url; the shipped servers.json may carry a bare hash.
  const raw = typeof server.icon === 'string' ? server.icon.trim() : '';
  let src = '';
  if (/^https?:\/\//i.test(raw)) src = raw;
  else if (raw && server.id && !String(server.id).startsWith('example-')) {
    const ext = raw.startsWith('a_') ? 'gif' : 'png';
    src = `https://cdn.discordapp.com/icons/${server.id}/${raw}.${ext}?size=128`;
  }
  if (src) {
    const img = document.createElement('img');
    img.src = src;
    img.alt = '';
    img.loading = 'lazy';
    img.decoding = 'async';
    img.addEventListener(
      'error',
      () => {
        img.remove();
        icon.textContent = initials(server.name);
      },
      { once: true },
    );
    icon.appendChild(img);
  } else {
    icon.textContent = initials(server.name);
  }

  const info = document.createElement('span');
  info.className = 'server-info';

  const name = document.createElement('span');
  name.className = 'server-name';
  name.textContent = server.name;

  const meta = document.createElement('span');
  meta.className = 'server-meta';
  meta.innerHTML = USERS_ICON;
  meta.append(members ? `${members} members` : 'Community');

  info.append(name, meta);
  card.append(icon, info);
  return card;
}

function emptyCard(href = '#support') {
  const card = document.createElement('a');
  card.className = 'server-card';
  card.href = href;
  card.innerHTML =
    '<span class="server-icon" aria-hidden="true">+</span>' +
    '<span class="server-info"><span class="server-name">Your server here</span>' +
    '<span class="server-meta">Be the first to invite Kernel</span></span>';
  return card;
}

/* A row of cards that loops forever. The extra cards keep the loop seamless. */
function marqueeRow(servers, { speed = 60, reverse = false } = {}) {
  const marquee = document.createElement('div');
  marquee.className = 'marquee' + (reverse ? ' is-reverse' : '');

  const track = document.createElement('div');
  track.className = 'marquee-track';

  const group = document.createElement('div');
  group.className = 'marquee-group';
  servers.forEach((server) => group.append(serverCard(server)));

  track.append(group);
  marquee.append(track);
  return { marquee, track, group, speed };
}

function fillMarquee(row) {
  const { marquee, track, group, speed } = row;
  const originals = Array.from(group.children);
  if (!originals.length) return;

  const viewport = marquee.getBoundingClientRect().width;
  if (!viewport) return;

  const width = () => group.getBoundingClientRect().width;
  let guard = 0;
  while (width() < viewport * 1.15 && guard < 20) {
    originals.forEach((node) => {
      const clone = node.cloneNode(true);
      clone.setAttribute('aria-hidden', 'true');
      group.append(clone);
    });
    guard += 1;
  }

  const duplicate = group.cloneNode(true);
  duplicate.setAttribute('aria-hidden', 'true');
  track.append(duplicate);

  const loopWidth = width();
  if (loopWidth > 0) {
    marquee.style.setProperty('--marquee-duration', Math.max(14, Math.round(loopWidth / speed)) + 's');
  }
}

function watchMarquees(rows) {
  if (!('IntersectionObserver' in window)) return;
  const io = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => entry.target.classList.toggle('is-paused', !entry.isIntersecting));
    },
    { rootMargin: '160px 0px' },
  );
  rows.forEach((row) => io.observe(row.marquee));
}

/* The bot publishes its own server list, so the showcase is real without regenerating a file.
 * A saved servers.json (or the examples below) covers the case where the bot is not reachable. */
async function fetchLiveServers() {
  const base =
    typeof window.KERNEL_API_BASE === 'string' ? window.KERNEL_API_BASE.trim().replace(/\/+$/, '') : '';
  if (!base) return null;
  const controller = new AbortController();
  const timer = window.setTimeout(() => controller.abort(), 3500);
  try {
    const response = await fetch(base + '/api/public/servers', {
      cache: 'no-store',
      headers: { 'ngrok-skip-browser-warning': '1' },
      signal: controller.signal,
    });
    if (!response.ok) return null;
    const data = await response.json();
    if (!data || data.sample !== false || !Array.isArray(data.servers)) return null;
    return data;
  } catch (error) {
    return null;
  } finally {
    window.clearTimeout(timer);
  }
}

async function setupServers() {
  const preview = document.querySelector('[data-servers-preview]');
  const grid = document.querySelector('[data-servers-grid]');
  const staticGrid = document.querySelector('[data-servers-static]');
  const countEl = document.querySelector('[data-servers-count]');
  const note = document.querySelector('[data-servers-note]');
  if (!preview && !grid && !staticGrid) return;

  let payload = await fetchLiveServers();
  if (!payload) {
    try {
      const response = await fetch('servers.json', { cache: 'no-store' });
      if (!response.ok) throw new Error('HTTP ' + response.status);
      const data = await response.json();
      if (!data || !Array.isArray(data.servers)) throw new Error('Unexpected servers.json shape');
      payload = data;
    } catch (error) {
      payload = { sample: true, servers: SAMPLE_SERVERS };
    }
  }

  const sample = payload.sample !== false;
  const filtered = payload.servers.filter(
    (server) => server && typeof server.name === 'string' && server.name.trim(),
  );
  // The owner can hide or reorder the showcase from the console. Wait briefly for that copy, but
  // never stall the page on a sleeping bot: past 1.2s the shipped order is used.
  if (window.KernelSite && window.KernelSite.ready) {
    await Promise.race([
      window.KernelSite.ready,
      new Promise((resolve) => setTimeout(resolve, 1200)),
    ]);
  }
  const servers =
    window.KernelSite && typeof window.KernelSite.showcase === 'function'
      ? window.KernelSite.showcase(filtered)
      : filtered;

  const rows = [];

  if (preview) {
    preview.replaceChildren();
    if (servers.length) {
      const sides = [[], []];
      servers.slice(0, 8).forEach((server, index) => sides[index % 2].push(server));
      sides.forEach((items, index) => {
        if (!items.length) return;
        const row = marqueeRow(items, { speed: index === 1 ? 52 : 44, reverse: index === 1 });
        preview.append(row.marquee);
        rows.push(row);
      });
    } else {
      preview.append(emptyCard());
    }
  }

  if (grid) {
    grid.replaceChildren();
    if (servers.length) {
      const sides = [[], []];
      servers.forEach((server, index) => sides[index % 2].push(server));
      sides.forEach((items, index) => {
        if (!items.length) return;
        const row = marqueeRow(items, { speed: 62, reverse: index === 1 });
        grid.append(row.marquee);
        rows.push(row);
      });
    } else {
      grid.append(emptyCard());
    }
  }

  if (staticGrid) {
    staticGrid.replaceChildren();
    if (servers.length) {
      servers.forEach((server) => staticGrid.append(serverCard(server)));
    } else {
      staticGrid.append(emptyCard('index.html#support'));
    }
  }

  if (rows.length) {
    window.requestAnimationFrame(() => {
      rows.forEach(fillMarquee);
      watchMarquees(rows);
    });
  }

  if (note) note.hidden = !sample;

  if (countEl) {
    if (!servers.length) {
      countEl.textContent = 'No communities listed yet';
    } else {
      const totalMembers = servers.reduce((sum, server) => sum + (Number(server.memberCount) || 0), 0);
      const label = sample
        ? `${servers.length} example ${servers.length === 1 ? 'community' : 'communities'}`
        : `${servers.length} ${servers.length === 1 ? 'community' : 'communities'} listed`;
      countEl.textContent = totalMembers
        ? `${label} · ${new Intl.NumberFormat('en').format(totalMembers)} members`
        : label;
    }
  }

  setHeroTotals(servers, !sample);
}

function setHeroTotals(servers, live) {
  const wrap = document.querySelector('[data-hero-powering]');
  if (!wrap) return;
  if (!live || !servers.length) {
    wrap.hidden = true;
    return;
  }

  const totalMembers = servers.reduce((sum, server) => sum + (Number(server.memberCount) || 0), 0);
  const count = wrap.querySelector('[data-hero-servers]');
  const members = wrap.querySelector('[data-hero-members]');
  const membersWrap = wrap.querySelector('.powering-members');
  if (membersWrap) membersWrap.hidden = totalMembers <= 0;
  if (count) {
    count.textContent = String(servers.length);
    count.dataset.countTo = String(servers.length);
  }
  if (members) {
    members.textContent = formatCount(totalMembers) || '0';
    members.dataset.countTo = String(totalMembers);
    members.dataset.format = 'compact';
  }
  wrap.hidden = false;
  // motion.js animates counters it has not seen yet; without it the final value stays on screen.
  document.dispatchEvent(new CustomEvent('kernel:counters'));
}

/* The hero pill reads the bot's own health route, so "Online" only appears when the API answered. */
function setupHeroStatus() {
  const pill = document.querySelector('[data-hero-status-pill]');
  const label = document.querySelector('[data-hero-status]');
  if (!pill || !label) return;

  const base =
    typeof window.KERNEL_API_BASE === 'string' ? window.KERNEL_API_BASE.trim().replace(/\/+$/, '') : '';
  if (!base) {
    label.textContent = 'Live status on the status page';
    return;
  }

  const controller = new AbortController();
  const timer = window.setTimeout(() => controller.abort(), 4000);
  fetch(base + '/api/health', {
    cache: 'no-store',
    headers: { 'ngrok-skip-browser-warning': '1' },
    signal: controller.signal,
  })
    .then((response) => (response.ok ? response.json() : Promise.reject(new Error('HTTP ' + response.status))))
    .then((data) => {
      if (!data || data.ok !== true) throw new Error('Unexpected health payload');
      pill.classList.add('is-live');
      label.textContent = data.ready === false ? 'Online · gateway starting' : 'Online · gateway ready';
    })
    .catch(() => {
      pill.classList.add('is-down');
      label.textContent = 'Status page · live checks';
    })
    .finally(() => window.clearTimeout(timer));
}

/* --------------------------------------------------------------- bootstrap */

function boot() {
  applyConfig();
  setupAuthUI();
  setupNav();
  setupReveals();
  setupDirectory();
  setupHeroStatus();

  const year = document.getElementById('year');
  if (year) year.textContent = String(new Date().getFullYear());

  setupServers().catch(() => {
    /* The fallback cards are rendered inside setupServers itself. */
  });
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', boot);
} else {
  boot();
}
